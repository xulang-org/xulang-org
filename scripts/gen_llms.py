#!/usr/bin/env python3
"""Render LLM documentation from site metadata and shared Xu examples."""

from __future__ import annotations

import json
from html import unescape
from pathlib import Path
import re


def project_source(project: dict) -> str:
    """Export a root-package project as one complete, runnable main.xu."""
    files = project['files']
    entry = project['entry']
    paths = sorted(path for path in files if '/' not in path and path.endswith('.xu'))
    paths.remove(entry)
    paths.insert(0, entry)
    sources = [re.sub(r'(?m)^\s*@main\s*$', '', files[path]).strip() for path in paths]
    return '@main\n\n' + '\n\n'.join(sources) + '\n'


def render_corpora(root: Path, xu_version: str) -> dict[str, str]:
    metadata = json.loads((root / 'www/benchmarks.json').read_text())['metadata']
    playground = json.loads((root / 'www/xu-play-examples.json').read_text())
    examples = {name: project_source(item) for name, item in playground['projects'].items()}
    examples['errors'] = (root / 'www/api-examples/sources/examples/05_errors/main.xu').read_text()
    tutorial = (root / 'content/en/docs/tutorial/06.html').read_text()
    examples['ownership'] = unescape(re.search(r'<pre><code>(.*?)</code></pre>', tutorial, re.S)[1])
    values = {
        'xu_version': xu_version,
        'benchmark_version': metadata['xu_version'],
        'benchmark_date': metadata['date'],
        'benchmark_count': str(metadata['total_benches']),
        'benchmark_platforms': str(len(metadata['platforms'])),
        'benchmark_run': metadata['run_url'],
    }

    def expand(name: str) -> str:
        source = (root / 'templates/llms' / name).read_text()

        def replace(match: re.Match) -> str:
            key = match[1]
            if key.startswith('example:'):
                return '```xu\n' + examples[key.removeprefix('example:')].rstrip() + '\n```'
            return values[key]

        return re.sub(r'\{\{([a-z_:.-]+)\}\}', replace, source)

    overview = expand('overview.md')
    reference = expand('reference.md')
    notice = '<!-- Generated by scripts/gen_llms.py; edit templates/llms/*.md and shared example sources. -->\n'
    return {
        'llms.txt': overview.rstrip() + '\n\n' + notice,
        'llms-full.txt': overview.rstrip() + '\n\n' + reference.rstrip() + '\n\n' + notice,
    }


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    for name, source in render_corpora(root, (root / 'VERSION').read_text().strip()).items():
        (root / 'www' / name).write_text(source, encoding='utf-8')
        print('wrote www/' + name)
